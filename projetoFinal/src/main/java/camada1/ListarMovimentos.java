    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String texto = "";
        Collections.sort(conta.getMovimentos(), new OrdenarPorData());
        
        if(DESPESA.isSelected()) {   
            
            for(Movimento m : conta.getMovimentos()) {
                if(m instanceof Despesa) {
                    texto += m.getData() + " | R$: " + m.getValor() + " | Categoria: " + m.getCategoria() + "\n";
                }
            }
        } else if(RECEITA.isSelected()) {
            for (Movimento m : conta.getMovimentos()) {
                if (m instanceof Receita) {
                    texto += m.getData() + " | R$: " + m.getValor() + " | Categoria: " + m.getCategoria() + "\n";
                }
            }
        } else if(TODOS.isSelected()) {
            Double saldo = 0.0;
            for (Movimento m : conta.getMovimentos()) {
                if(m instanceof Receita) {
                    saldo += m.getValor();
                    texto += m.getData() + " | Saldo: R$" + saldo + " | Valor: " + m.getValor() + " | Categoria: " + m.getCategoria() + "\n";
                } else if(m instanceof Despesa) {
                    saldo -= m.getValor();
                    texto += m.getData() + " | Saldo: R$" + saldo + " | Valor: -" + m.getValor() + " | Categoria: " + m.getCategoria() + "\n";
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "Escolha o tipo de movimento a ser listado!");
        }
        
        jTextArea1.setText(texto);
    }//GEN-LAST:event_jButton1ActionPerformed

